#!/usr/bin/env python3
"""src/cs/e3b/lp_gen.py -- E3b: write a Singular script for one gcd pattern in LUCAS-POINT coordinates (k = 5).
A = x^2 - 1.  Member i with a Lucas point th_i:  f_i = n_i / D_i,  D_i = (th_i^2 - 1)(th_i - r_i),
n_i(x) = D_i - 2 (x^2 - 1)(x - r_i)   (so f_i(th_i) = -1, f_i(r_i) = 1, f_i - 1 = A g_i, g_i = -2 (x - r_i)/D_i);
member 1: D_1 = w^2 - 1, n_1 = D_1 - 2 (x^2 - 1)  (Lucas points +-w).  A member without Lucas point keeps
n_i = 1 + (x^2 - 1) g_i, D_i = 1 (g_1 = c, g_i = l_i (x - r_i)).
Equations (all polynomial, exact):
  Korselt_j (j = 2..5): [prod_{i != j} n_i(r_j) - prod_{i != j} D_i] / (r_j^2 - 1)  (exact division; = D-scaled K_j)
  Lucas at a point t of member j:  prod_{i != j} n_i(t) - prod_{i != j} D_i
  2nd / 3rd Lucas point t', t'' of cubic member j (other roots of f_j + 1): divided differences of
     E(t) = (t^2 - 1)(t - r_j):  [E(t') - E(th)]/(t' - th) = 0,  [[E](t'', th, t')] = 0   (excludes coincidences).
  member 1 second Lucas point is -w (automatic root of f_1 + 1).
Saturation (sequentially) by: every D_i, r_i - r_j, and 1 + w (w^2 != 1 is inside D_1).
Output: <name>.sing computing dim (and vdim if 0) of the saturated ideal over the chosen characteristic.
Usage: lp_gen.py "m1,..,m5" char name [extra-singular-lines-file]
"""
import sys
m = [int(t) for t in sys.argv[1].split(',')]; ch = sys.argv[2]; name = sys.argv[3]
vars_ = ['r2', 'r3', 'r4', 'r5']
mem = []
for j in range(5):
    J = j + 1
    if m[j] == 0:
        if J == 1:
            vars_.append('c'); mem.append(dict(n='1 + (x^2 - 1)*c', D='1', pts=[]))
        else:
            vars_.append('l%d' % J); mem.append(dict(n='1 + (x^2 - 1)*l%d*(x - r%d)' % (J, J), D='1', pts=[]))
    elif J == 1:
        vars_.append('w')
        mem.append(dict(n='(w^2 - 1) - 2*(x^2 - 1)', D='(w^2 - 1)', pts=['w', '(-w)'][:m[0]]))
    else:
        th = ['t%d%d' % (J, s) for s in range(1, m[j] + 1)]
        vars_ += th
        D = '((t%d1^2 - 1)*(t%d1 - r%d))' % (J, J, J)
        mem.append(dict(n='%s - 2*(x^2 - 1)*(x - r%d)' % (D, J), D=D, pts=th))
L = []
L.append('// generated by lp_gen.py pattern %s char %s' % (m, ch))
L.append('LIB "elim.lib";')
L.append('proc SAT(ideal I, poly g) { def S = sat(I, g); if (typeof(S) == "list") { ideal J = S[1]; return(J); } return(S); }')
L.append('system("--ticks-per-sec", 1000);')
L.append('ring R = %s, (x, %s), dp;' % (ch, ', '.join(vars_)))
for j in range(5):
    L.append('poly n%d = %s; poly D%d = %s;' % (j + 1, mem[j]['n'], j + 1, mem[j]['D']))
L.append('ideal I;')
for J in range(2, 6):
    others = [i for i in range(1, 6) if i != J]
    pn = '*'.join('subst(n%d, x, r%d)' % (i, J) for i in others)
    pd = '*'.join('D%d' % i for i in others)
    L.append('I[size(I) + 1] = division(%s - %s, r%d^2 - 1)[1][1,1];' % (pn, pd, J))
for j in range(5):
    J = j + 1
    others = [i for i in range(1, 6) if i != J]
    for s, t in enumerate(mem[j]['pts']):
        pn = '*'.join('subst(n%d, x, %s)' % (i, t) for i in others)
        pd = '*'.join('D%d' % i for i in others)
        L.append('I[size(I) + 1] = %s - %s;' % (pn, pd))
    if J >= 2 and m[j] >= 2:
        th = mem[j]['pts']
        L.append('poly E%d = (x^2 - 1)*(x - r%d);' % (J, J))
        # first divided difference [E](th1, th2)
        L.append('poly dd%d = division(subst(E%d, x, %s) - subst(E%d, x, %s), %s - %s)[1][1,1];' % (J, J, th[1], J, th[0], th[1], th[0]))
        L.append('I[size(I) + 1] = dd%d;' % J)
        if m[j] == 3:
            # second divided difference [E](th1, th2, th3) = ([E](th1,th3) - [E](th1,th2)) / (th3 - th2)
            L.append('poly dd%db = division(subst(E%d, x, %s) - subst(E%d, x, %s), %s - %s)[1][1,1];' % (J, J, th[2], J, th[0], th[2], th[0]))
            L.append('I[size(I) + 1] = division(dd%db - dd%d, %s - %s)[1][1,1];' % (J, J, th[2], th[1]))
sat_list = ['D%d' % (j + 1) for j in range(5) if mem[j]['D'] != '1']
sat_list += ['r%d - r%d' % (a, b) for a in range(2, 6) for b in range(a + 1, 6)]
for j in range(5):
    if m[j] == 0:
        sat_list.append('c' if j == 0 else 'l%d' % (j + 1))
L.append('int t0 = rtimer;')
L.append('ring S = %s, (%s), dp;' % (ch, ', '.join(vars_)))
L.append('ideal I = imap(R, I);')
L.append('"pattern %s: ", size(I), " equations in %d unknowns";' % (m, len(vars_)))
L.append('ideal J = I;')
for f in sat_list:
    if f.startswith('D'):
        f = mem[int(f[1:]) - 1]['D']
    L.append('poly sf = %s; J = SAT(J, sf); kill sf; "  sat %s, time ms ", rtimer - t0;' % (f, f))
L.append('ideal G = std(J); int d = dim(G);')
L.append('"RESULT pattern %s: dim ", d, " vdim ", vdim(G), "  time ms ", rtimer - t0;' % m)
L.append('write(":w %s.res", "pattern %s dim " + string(d) + " vdim " + string(vdim(G)));' % (name, m))
L.append('quit;')
open(name + '.sing', 'w').write('\n'.join(L) + '\n')
