#!/usr/bin/env python3
"""src/cs/e3b/sym_gen.py -- E3b: Singular scripts for gcd strata on the x -> -x SYMMETRIC locus, Lucas-point coordinates.
Members: 1 (even), 2 and 3 = mirror of 2 (f_3(x) = f_2(-x)), 4 and 5 = mirror of 4.  A = x^2 - 1.
A member with a Lucas point th: f(x) = n(x)/D, D = (th^2 - 1)(th - r), n = D - 2 (x^2 - 1)(x - r);
mirror: f(-x) = n(-x)/D.  Member 1 with Lucas point w: n_1 = (w^2 - 1) - 2 (x^2 - 1), D_1 = w^2 - 1;
member without Lucas point: coefficient variable.
Pattern (m1, m2, m4): m1 in {0, 2} (sym forces evenness), m2 = m3, m4 = m5 in 0..3.  Sum m = m1 + 2 m2 + 2 m4.
Equations: Korselt for members 2 and 4 (3 and 5 follow by symmetry): [prod_{i != j} n_i(r_j) - prod D_i]/(r_j^2 - 1);
Lucas at each Lucas point (member 1: w only; -w by symmetry); 2nd/3rd Lucas points of 2 / 4 via divided differences.
Saturation by D_i, r2, r4, r2 -+ r4, coefficient variables.  Output: dim / vdim, and (if 0-dim) the eliminant in one var.
Usage: sym_gen.py m1 m2 m4 CHAR name
"""
import sys
m1, m2, m4 = map(int, sys.argv[1:4]); ch = sys.argv[4]; name = sys.argv[5]
V = ['r2', 'r4']; n = {}; D = {}; lp = {}
if m1 == 0:
    V.append('c'); n[1] = '1 + (x^2 - 1)*c'; D[1] = '1'; lp[1] = []
else:
    V.append('w'); n[1] = '(w^2 - 1) - 2*(x^2 - 1)'; D[1] = '(w^2 - 1)'; lp[1] = ['w']
for j, mj in ((2, m2), (4, m4)):
    if mj == 0:
        V.append('l%d' % j); n[j] = '1 + (x^2 - 1)*l%d*(x - r%d)' % (j, j); D[j] = '1'; lp[j] = []
    else:
        th = ['t%d%d' % (j, s) for s in range(1, mj + 1)]; V += th
        D[j] = '((t%d1^2 - 1)*(t%d1 - r%d))' % (j, j, j)
        n[j] = '%s - 2*(x^2 - 1)*(x - r%d)' % (D[j], j); lp[j] = th
L = ['// generated by sym_gen.py %d %d %d char %s' % (m1, m2, m4, ch), 'LIB "elim.lib";',
     'proc SAT(ideal I, poly g) { def S = sat(I, g); if (typeof(S) == "list") { ideal J = S[1]; return(J); } return(S); }',
     'system("--ticks-per-sec", 1000);',
     'ring R = %s, (x, %s), dp;' % (ch, ', '.join(V))]
for j in (1, 2, 4):
    L.append('poly n%d = %s; poly D%d = %s;' % (j, n[j], j, D[j]))
L.append('poly n3 = subst(n2, x, -x); poly D3 = D2; poly n5 = subst(n4, x, -x); poly D5 = D4;')
L.append('ideal I;')
for j, rj in ((2, 'r2'), (4, 'r4')):
    others = [i for i in range(1, 6) if i != j]
    pn = '*'.join('subst(n%d, x, %s)' % (i, rj) for i in others)
    pd = '*'.join('D%d' % i for i in others)
    L.append('I[size(I) + 1] = division(%s - %s, %s^2 - 1)[1][1,1];' % (pn, pd, rj))
for j in (1, 2, 4):
    others = [i for i in range(1, 6) if i != j]
    for t in lp[j]:
        pn = '*'.join('subst(n%d, x, %s)' % (i, t) for i in others)
        pd = '*'.join('D%d' % i for i in others)
        L.append('I[size(I) + 1] = %s - %s;' % (pn, pd))
for j, mj in ((2, m2), (4, m4)):
    if mj >= 2:
        th = lp[j]
        L.append('poly E%d = (x^2 - 1)*(x - r%d);' % (j, j))
        L.append('poly dd%d = division(subst(E%d, x, %s) - subst(E%d, x, %s), %s - %s)[1][1,1];' % (j, j, th[1], j, th[0], th[1], th[0]))
        L.append('I[size(I) + 1] = dd%d;' % j)
        if mj == 3:
            L.append('I[size(I) + 1] = %s + %s + %s - r%d;' % (th[0], th[1], th[2], j))
sat = [D[j] for j in (1, 2, 4) if D[j] != '1'] + ['r2', 'r4', 'r2 - r4', 'r2 + r4']
if m1 == 0: sat.append('c')
for j, mj in ((2, m2), (4, m4)):
    if mj == 0: sat.append('l%d' % j)
    if mj >= 2: sat.append('%s - %s' % (lp[j][0], lp[j][1]))
    if mj == 3: sat += ['%s - %s' % (lp[j][0], lp[j][2]), '%s - %s' % (lp[j][1], lp[j][2])]
L.append('ring S = %s, (%s), dp;' % (ch, ', '.join(V)))
L.append('ideal I = imap(R, I); int t0 = rtimer; ideal J = I;')
L.append('"pattern (m1,m2,m4) = (%d,%d,%d), Sum m = %d: ", size(I), " equations, %d unknowns";' % (m1, m2, m4, m1 + 2*m2 + 2*m4, len(V)))
for f in sat:
    L.append('poly sf = %s; J = SAT(J, sf); kill sf;' % f)
L.append('ideal G = std(J); int d = dim(G);')
L.append('"RESULT (%d,%d,%d): dim ", d, " vdim ", vdim(G), "  time ms ", rtimer - t0;' % (m1, m2, m4))
L.append('if (d == 0) { ideal El = eliminate(G, %s); "eliminant in %s: degree ", deg(El[1]); list fa = factorize(El[1]); int i; for (i = 1; i <= size(fa[1]); i++) { if (deg(fa[1][i]) > 0) { "  factor deg ", deg(fa[1][i]), " mult ", fa[2][i]; if (deg(fa[1][i]) <= 2) { fa[1][i]; } } } }' % ('*'.join(V[1:]), V[0]))
L.append('write(":a %s.res", "(%d,%d,%d) dim " + string(d) + " vdim " + string(vdim(G)));' % (name, m1, m2, m4))
L.append('quit;')
open(name + '.sing', 'w').write('\n'.join(L) + '\n')
